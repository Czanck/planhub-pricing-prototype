/** Representative file list (capped at the library size; headline count is `fileCount`). */
function files(prefix: string, n: number): ProjectFile[] {
  return FILE_LIB.slice(0, Math.min(n, FILE_LIB.length)).map((f, i) => ({
    id: `${prefix}-f${i + 1}`,
    name: f[0],
    category: f[1],
    type: f[2],
    sizeMb: f[3],
    uploaded: UP,
  }))
}

function gc(
  prefix: string,
  i: number,
  name: string,
  biddingStatus: GeneralContractor['biddingStatus'],
  bidDue: string,
  contactName: string,
  phone: string,
  email: string,
): GeneralContractor {
  return { id: `${prefix}-gc${i}`, name, biddingStatus, bidDue, contactName, phone, email }
}

function intel(
  views: number,
  intendToBid: number,
  bidsSubmitted: number,
  bars: Array<[string, number]>,
): MarketIntel {
  return {
    views,
    intendToBid,
    bidsSubmitted,
    demandByTrade: bars.map(([trade, count]) => ({ trade, count })),
  }
}

function fit(
  reason: string,
  match: string[],
  timeline: string,
  winOdds: string,
  goNoGo: ProjectFit['goNoGo'] = 'Go',
  headline = 'Likely a strong fit',
  sizeLabel = 'Yes',
): ProjectFit {
  return {
    headline,
    blurredReason: reason,
    matchesTrades: { value: match.length > 0, trades: match },
    withinJobSize: { value: sizeLabel === 'Yes', label: sizeLabel },
    timelineVsCapacity: timeline,
    winOddsVsCompetition: winOdds,
    goNoGo,
  }
}

